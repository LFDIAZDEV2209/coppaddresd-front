/** Presentación de fecha civil: UTC en ambos extremos evita desplazar el día. */
export function formatNutritionDate(value: string, locale: string) {
  return new Intl.DateTimeFormat(locale, {
    day: "numeric",
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${value}T00:00:00Z`));
}
